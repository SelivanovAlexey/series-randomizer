CREATE TABLE episodes (
                         id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         series_id BIGINT       NOT NULL,
                         season    INT          NOT NULL,
                         number    INT          NOT NULL,
                         title     VARCHAR(255),
                         watched   BOOLEAN      NOT NULL DEFAULT FALSE,
                         CONSTRAINT fk_episodes_series FOREIGN KEY (series_id) REFERENCES series (id),
                         CONSTRAINT uq_episodes_series_season_number UNIQUE (series_id, season, number)
);